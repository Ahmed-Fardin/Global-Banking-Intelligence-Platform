DROP TABLE IF EXISTS bank_financials_usd;

CREATE TABLE bank_financials_usd
(
    financial_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    iso3_code CHAR(3) NOT NULL,
    bank_name VARCHAR(200) NOT NULL,
    fiscal_year INTEGER NOT NULL,

    total_assets NUMERIC(24,2),
    total_deposits NUMERIC(24,2),
    total_loans NUMERIC(24,2),
    shareholders_equity NUMERIC(24,2),
    operating_income NUMERIC(24,2),
    net_income NUMERIC(24,2),

    roe_percent NUMERIC(10,2),
    roa_percent NUMERIC(10,2),
    capital_adequacy_percent NUMERIC(10,2),
    cost_income_ratio NUMERIC(10,2),
    loan_to_deposit_ratio NUMERIC(10,2),
    npl_ratio NUMERIC(10,2),

    employees INTEGER,
    branches INTEGER,

    reporting_currency VARCHAR(10),
    source TEXT,

    CONSTRAINT uq_bank_financials_usd_year
        UNIQUE (iso3_code, bank_name, fiscal_year),

    CONSTRAINT fk_financials_usd_country
        FOREIGN KEY (iso3_code)
        REFERENCES countries(iso3_code)
);

CREATE INDEX idx_bank_financials_usd_year
    ON bank_financials_usd(fiscal_year);

CREATE INDEX idx_bank_financials_usd_bank
    ON bank_financials_usd(bank_name);

CREATE INDEX idx_bank_financials_usd_country
    ON bank_financials_usd(iso3_code);